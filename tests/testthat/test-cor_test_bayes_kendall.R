# The 36 cells of the AC2 grid: each numeric-scale row, plus the "medium" cells
# (which must equal the 1/3 cells exactly).
.grid_scales <- function(scale) {
  if (isTRUE(all.equal(scale, 1 / 3))) list(1 / 3, "medium") else list(1)
}

test_that("AC1: cor_test and correlation report a Bayesian Kendall row", {
  out <- cor_test(mtcars, "mpg", "cyl", method = "kendall", bayesian = TRUE)
  expect_s3_class(out, "easycor_test")
  expect_identical(nrow(out), 1L)
  for (col in c(
    "tau",
    "CI",
    "CI_low",
    "CI_high",
    "pd",
    "ROPE_Percentage",
    "Prior_Distribution",
    "Prior_Location",
    "Prior_Scale",
    "BF",
    "Method",
    "n_Obs"
  )) {
    expect_true(col %in% names(out), label = paste("column", col))
  }
  expect_identical(out$Method, "Bayesian Kendall")
  expect_identical(attr(out, "coefficient_name"), "tau")

  # The tied pair reports the helper's BF at n = 32 and the observed tau-b.
  tau_b <- stats::cor(mtcars$mpg, mtcars$cyl, method = "kendall")
  ref <- .bk(n = 32, tau = tau_b, scale = "medium", ci_method = "hdi")
  expect_identical(out$n_Obs, 32L)
  expect_equal(out$BF, ref$BF)
  expect_equal(out$tau, ref$tau)

  skip_if_not_installed("BayesFactor")
  ken <- correlation(mtcars[, 1:3], method = "kendall", bayesian = TRUE)
  pea <- correlation(mtcars[, 1:3], method = "pearson", bayesian = TRUE)
  expect_identical(nrow(ken), 3L)
  expect_true(all(ken$Method == "Bayesian Kendall correlation"))
  expect_true("tau" %in% names(ken))
  # The #224 reprex: every row differs from the Bayesian Pearson estimate.
  expect_true(all(abs(ken$tau - pea$rho) > 1e-3))
})

test_that("AC1: bayesian_test selects the reported tests as the Pearson row does", {
  out <- cor_test(
