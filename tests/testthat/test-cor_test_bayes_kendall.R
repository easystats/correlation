test_that("AC2: the helper matches the paper's OSF code and bstats on the 36-cell grid", {
  ref <- bayes_kendall_reference
  for (i in seq_len(nrow(ref))) {
    for (scale in .grid_scales(ref$scale[i])) {
      lab <- sprintf(
        "n = %d, tau = %s, scale = %s",
        ref$n[i],
        ref$tau[i],
        format(scale)
      )
      res <- .bk(n = ref$n[i], tau = ref$tau[i], scale = scale)
      # BF: relative tolerance 1e-3 against both sources
      expect_lt(
        abs(res$BF / ref$osf_bf[i] - 1),
        1e-3,
        label = paste("OSF BF", lab)
      )
      expect_lt(
        abs(res$BF / ref$bstats_bf[i] - 1),
        1e-3,
        label = paste("bstats BF", lab)
      )
      # median and equal-tailed endpoints: absolute tolerance 3e-3
      expect_lt(
        abs(res$tau - ref$osf_median[i]),
        3e-3,
        label = paste("OSF median", lab)
      )
      expect_lt(
        abs(res$CI_low - ref$osf_low[i]),
        3e-3,
        label = paste("OSF low", lab)
      )
      expect_lt(
        abs(res$CI_high - ref$osf_high[i]),
        3e-3,
        label = paste("OSF high", lab)
      )
      expect_lt(
        abs(res$tau - ref$bstats_median[i]),
        3e-3,
        label = paste("bstats median", lab)
      )
      expect_lt(
        abs(res$CI_low - ref$bstats_low[i]),
        3e-3,
        label = paste("bstats low", lab)
      )
      expect_lt(
        abs(res$CI_high - ref$bstats_high[i]),
        3e-3,
        label = paste("bstats high", lab)
      )
    }
    if (isTRUE(all.equal(ref$scale[i], 1 / 3))) {
      a <- .bk(n = ref$n[i], tau = ref$tau[i], scale = 1 / 3)
      b <- .bk(n = ref$n[i], tau = ref$tau[i], scale = "medium")
      keys <- c("tau", "CI_low", "CI_high", "pd", "ROPE_Percentage", "BF")
      expect_identical(a[keys], b[keys])
    }
  }
})

test_that("AC3: the Fig. 5 brain-size example reproduces", {
  d <- .read_brain_size()
  expect_identical(nrow(d), 20L)
  out <- cor_test(
    d,
    "FSIQ",
    "MRI_Count",
    method = "kendall",
    bayesian = TRUE,
    bayesian_prior = 1,
    bayesian_ci_method = "eti"
  )
  expect_lt(abs(out$BF - 2.170), 0.005)
  expect_lt(abs(out$tau - 0.291), 0.005)
  expect_lt(abs(out$CI_low - 0.006), 0.005)
  expect_lt(abs(out$CI_high - 0.571), 0.005)

  skip_if_not_installed("BayesFactor")
  pea <- cor_test(d, "FSIQ", "MRI_Count", bayesian = TRUE, bayesian_prior = 1)
  expect_lt(abs(pea$BF - 5.158), 0.005)
})

test_that("AC4: at tau = 0 and scale 1 the BF is the integral of eqs. (10) and (13)", {
  for (n in c(5, 20, 100)) {
    # eq. (10): p(tau) = (pi/4) cos(pi tau / 2); eq. (13) with T* = 0:
    # BF10 = integral of exp(-(1.5 tau sqrt(n))^2 / 2) * p(tau) over [-1, 1].
    integrand <- function(tau) {
      exp(-(1.5 * tau * sqrt(n))^2 / 2) * (pi / 4) * cos(pi * tau / 2)
    }
    bf_closed <- stats::integrate(integrand, -1, 1, rel.tol = 1e-10)$value
    res <- .bk(n = n, tau = 0, scale = 1)
    expect_lt(abs(res$BF / bf_closed - 1), 1e-6, label = paste("n =", n))
    expect_lt(abs(res$tau), 1e-6, label = paste("median, n =", n))
    expect_lt(
      abs(res$CI_low + res$CI_high),
      1e-6,
      label = paste("endpoints, n =", n)
    )
  }
})

test_that("AC4: mirror symmetry in the observed tau", {
  ref <- bayes_kendall_reference
  for (i in seq_len(nrow(ref))) {
    for (scale in .grid_scales(ref$scale[i])) {
      lab <- sprintf(
        "n = %d, tau = %s, scale = %s",
        ref$n[i],
        ref$tau[i],
        format(scale)
      )
      plus <- .bk(n = ref$n[i], tau = ref$tau[i], scale = scale)
      minus <- .bk(n = ref$n[i], tau = -ref$tau[i], scale = scale)
      expect_lt(abs(minus$BF / plus$BF - 1), 1e-9, label = paste("BF", lab))
      expect_lt(abs(minus$tau + plus$tau), 1e-6, label = paste("median", lab))
      expect_lt(
        abs(minus$CI_low + plus$CI_high),
        1e-6,
        label = paste("low", lab)
      )
      expect_lt(
        abs(minus$CI_high + plus$CI_low),
        1e-6,
        label = paste("high", lab)
      )
    }
  }
})

test_that("AC5: pd and ROPE_Percentage are masses of the same posterior", {
  ref <- bayes_kendall_reference
  for (i in seq_len(nrow(ref))) {
    for (scale in .grid_scales(ref$scale[i])) {
      lab <- sprintf(
        "n = %d, tau = %s, scale = %s",
        ref$n[i],
        ref$tau[i],
        format(scale)
      )
      res <- .bk(n = ref$n[i], tau = ref$tau[i], scale = scale)
      if (ref$tau[i] == 0) {
        expect_lt(abs(res$pd - 0.5), 1e-6, label = paste("pd at 0", lab))
      }
      excludes_zero <- res$CI_low > 0 || res$CI_high < 0
      expect_identical(
        res$pd > 0.975,
        excludes_zero,
        label = paste("pd vs interval", lab)
      )
      expect_gte(res$ROPE_Percentage, 0)
      expect_lte(res$ROPE_Percentage, 1)
      rope_mass <- stats::integrate(
        res$posterior,
        -0.1,
        0.1,
        rel.tol = 1e-8
      )$value
      expect_lt(
        abs(res$ROPE_Percentage - rope_mass),
        1e-4,
        label = paste("ROPE", lab)
      )
    }
  }
})

test_that("AC5: the default hdi interval is the highest-density interval", {
  d <- .read_brain_size()
  hdi <- cor_test(d, "FSIQ", "MRI_Count", method = "kendall", bayesian = TRUE)
  eti <- cor_test(
    d,
    "FSIQ",
    "MRI_Count",
    method = "kendall",
    bayesian = TRUE,
    bayesian_ci_method = "eti"
  )
  expect_identical(hdi$tau, eti$tau)
  expect_lte(hdi$CI_high - hdi$CI_low, eti$CI_high - eti$CI_low)
  expect_true(hdi$CI_low < hdi$tau && hdi$tau < hdi$CI_high)
  # The HDI carries the requested mass and has equal density at its ends.
  res <- .bk(
    n = 20,
    tau = stats::cor(d$FSIQ, d$MRI_Count, method = "kendall"),
    scale = "medium",
    ci_method = "hdi"
  )
  mass <- stats::integrate(
    res$posterior,
    res$CI_low,
    res$CI_high,
    rel.tol = 1e-8
  )$value
  expect_lt(abs(mass - 0.95), 1e-4)
  expect_lt(abs(res$posterior(res$CI_low) - res$posterior(res$CI_high)), 1e-3)
})

test_that("AC7: x == y and perfectly monotone pairs", {
  same <- cor_test(mtcars, "mpg", "mpg", method = "kendall", bayesian = TRUE)
  expect_identical(same$tau, 1)
  expect_identical(same$CI_low, 1)
  expect_identical(same$CI_high, 1)
  expect_identical(same$pd, 1)
  expect_identical(same$ROPE_Percentage, 0)
  expect_identical(same$BF, Inf)

  up <- data.frame(x = 1:10, y = (1:10)^2)
  down <- data.frame(x = 1:10, y = -(1:10)^3)
  for (prior in list("medium", 1)) {
    out_up <- cor_test(
      up,
      "x",
      "y",
      method = "kendall",
      bayesian = TRUE,
      bayesian_prior = prior
    )
    out_down <- cor_test(
      down,
      "x",
      "y",
      method = "kendall",
      bayesian = TRUE,
      bayesian_prior = prior
    )
    expect_gt(out_up$tau, 0)
    expect_lt(out_down$tau, 0)
    expect_true(all(is.finite(c(
      out_up$CI_low,
      out_up$CI_high,
      out_down$CI_low,
      out_down$CI_high
    ))))
    expect_gt(out_up$BF, 1)
    expect_gt(out_down$BF, 1)
  }
})
