# Bayesian Kendall's tau (van Doorn, Ly, Marsman & Wagenmakers 2018) ----------
#
# Oracle records (one line per oracle: id | type | asserting test | source and
# provenance). The asserting test is the record of the value; nothing here
# restates a number a test does not assert.
#
# K1  | frozen (two independent implementations) | "AC2: the helper matches
#       the paper's OSF code and bstats on the 36-cell grid"
#       | bayes_kendall_reference below: BF10, posterior median, and equal-tailed
#       95% interval from the paper's own R_Code_KendallBayesFactor.R
#       (https://osf.io/b9qhj/) and from AlexanderLyNL/bstats R/kendall.R at
#       commit 42d34c1; generated by data-raw/bayes_kendall_reference.R; both
#       sources evaluate the interval on a grid (steps 0.002 and 0.0005), which
#       the 3e-3 absolute tolerance on median and endpoints covers.
# K2  | frozen (published) | "AC3: the Fig. 5 brain-size example reproduces"
#       | van Doorn et al. (2018) Fig. 5, p. 307: Kendall BF10 2.170 and Pearson
#       BF10 5.158 read against the source (cairn/references/vandoorn2018.md);
#       median 0.291 and interval [0.006, 0.571] are the OSF code's values on
#       the same 20 rows (the printed interval does not reproduce from that
#       code). Data: tests/testthat/fixtures/brain_size.csv, FSIQ >= 130.
# K3  | closed-form | "AC4: at tau = 0 and scale 1 the BF is the integral of
#       eqs. (10) and (13)" | BF10 = integral over [-1, 1] of
#       exp(-(1.5 tau sqrt(n))^2 / 2) * (pi/4) cos(pi tau / 2), transcribed
#       from vandoorn2018 p. 305 and integrated with stats::integrate().
# K4  | invariant | "AC4: mirror symmetry in the observed tau"
#       | the model is even in tau: negating the observed tau keeps BF and
#       negates and swaps the median and interval endpoints.
# K5  | invariant | "AC5: pd and ROPE_Percentage are masses of the same
#       posterior" | pd and the interval must agree on excluding 0; the ROPE
#       mass recomputed by integrating the helper's own posterior density.
# K6  | live | "AC1: a Bayesian Kendall row differs from the Bayesian Pearson
#       row" | BayesFactor::correlationBF() on the raw data (what the package
#       returned under this method before, issue #224).

.bk <- function(n, tau, scale, ci = 0.95, ci_method = "eti") {
  .bayes_kendall_posterior(
    n = n,
    tau = tau,
    scale = scale,
    ci = ci,
    ci_method = ci_method
  )
}

.read_brain_size <- function() {
  d <- read.csv(
    test_path("fixtures", "brain_size.csv"),
    comment.char = "#"
  )
  d[d$FSIQ >= 130, ]
}

